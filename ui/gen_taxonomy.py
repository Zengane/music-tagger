r"""Generate ui/taxonomy.odin from mtag/taxonomy.py.

The Python module stays the single source of truth for the tag vocabulary, so
editing a tag there and re-running this script is the only way the Odin UI's
copy changes. Run it after any edit to mtag/taxonomy.py:

    venv\Scripts\python.exe ui\gen_taxonomy.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mtag import kinds as K  # noqa: E402
from mtag import sfxtax  # noqa: E402
from mtag.media import vocab as media_vocab  # noqa: E402
from mtag import taxonomy as tx  # noqa: E402


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def slice_of(name: str, values) -> str:
    body = ", ".join(q(v) for v in values)
    return f"{name} := []string{{{body}}}\n"


def pairs_of(name: str, mapping: dict) -> str:
    rows = "".join(f"\t{{{q(k)}, {q(v)}}},\n" for k, v in sorted(mapping.items()))
    return f"{name} := [][2]string{{\n{rows}}}\n"


def phrases_of(name: str, mapping: dict) -> str:
    rows = ""
    for tag, phrases in sorted(mapping.items()):
        # Longest phrase first, so "super mario galaxy" beats "mario galaxy".
        ordered = sorted(phrases, key=len, reverse=True)
        body = ", ".join(q(p) for p in ordered)
        rows += f"\t{{{q(tag)}, {{{body}}}}},\n"
    return f"{name} := []Game_Phrases{{\n{rows}}}\n"


def sfx_groups_of(name: str, groups) -> str:
    rows = ""
    for group, tags in groups:
        body = ", ".join(q(t) for t in tags)
        rows += "\t{%s, {%s}},\n" % (q(group), body)
    return "%s := []Game_Phrases{\n%s}\n" % (name, rows)


def main() -> None:
    out = [
        "package musictagger\n\n",
        "// GENERATED by ui/gen_taxonomy.py from mtag/taxonomy.py. Do not edit.\n",
        "// Re-run the generator after changing the Python vocabulary.\n\n",
        "Game_Phrases :: struct {\n\ttag:     string,\n\tphrases: []string,\n}\n\n",
        slice_of("MOOD_TAGS", tx.MOOD_TAGS),
        "\n",
        slice_of("SOUND_TAGS", tx.SOUND_TAGS),
        "\n",
        slice_of("SFX_TAGS", tx.SFX_TAGS),
        "\n",
        slice_of("GAME_TAGS", tx.GAME_TAGS),
        "\n",
        slice_of("AUDIO_EXTS", sorted(tx.AUDIO_EXTS)),
        "\n",
        slice_of("SKIP_DIRS", tx.SKIP_DIRS),
        "\n",
        slice_of("SKIP_NAME_PATTERNS", tx.SKIP_NAME_PATTERNS),
        "\n",
        slice_of("CONTAINER_DIRS", sorted(tx.CONTAINER_DIRS)),
        "\n",
        slice_of("FAVORITE_TAGS", ["⭐", "★", "\U0001f31f", "☆"]),
        "\n",
        pairs_of("TAG_ALIASES", tx.TAG_ALIASES),
        "\n",
        pairs_of("GAME_ALIASES", tx.GAME_ALIASES),
        "\n",
        pairs_of("FOLDER_ALIASES", tx.FOLDER_ALIASES),
        "\n",
        phrases_of("GAME_PHRASES", tx.GAME_PHRASES),
        "\n",
        phrases_of("SFX_PHRASES", tx.SFX_PHRASES),
        "\n",
        # The effect vocabulary, grouped. Each pair is a category and its
        # tags, so the interface builds the categories from one table.
        sfx_groups_of("SFX_GROUPS", sfxtax.SFX_GROUPS),
        "\n",
        slice_of("SFX_INTENT_TAGS", sfxtax.SFX_INTENT),
        "\n",
        phrases_of("SFX_INTENT_PHRASES", tx.SFX_INTENT_PHRASES),
        "\n",
        # File kinds by extension, from mtag/kinds.py.
        slice_of("IMAGE_EXTS", K.EXTENSIONS[K.IMAGE]),
        "\n",
        slice_of("VIDEO_EXTS", K.EXTENSIONS[K.VIDEO]),
        "\n",
        slice_of("MODEL_EXTS", K.EXTENSIONS[K.MODEL]),
        "\n",
        slice_of("DOCUMENT_EXTS", K.EXTENSIONS[K.DOCUMENT]),
        "\n",
        # The vocabulary for images, video, 3D and documents, from
        # mtag/media/vocab.py and mtag/media/measure.py.
        sfx_groups_of("MEDIA_GROUPS", list(media_vocab.all_tags().items())),
    ]
    dest = ROOT / "ui" / "taxonomy.odin"
    dest.write_text("".join(out), encoding="utf-8")
    print(f"wrote {dest} ({dest.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
